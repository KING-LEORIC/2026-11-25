"""
RAG 평가 데이터셋 내 정답 부재(No-answer) 질문 분리 모듈.
Gold 청크가 비어 있는 질문을 식별해 검색 Recall 지표 왜곡을 방지하는 역할.
"""


def label_no_answer(question_id: str, gold: dict) -> bool:
    """해당 질문의 Gold 청크 목록이 비어 있는지 판별해 No-answer 여부를 반환하는 함수."""
    # 정답 청크가 없는 질문을 일반 질문과 합산하면 Recall이 무조건 0점으로 처리되어 평균 지표가 왜곡되므로,
    # 평가 파이프라인에서 별도 버킷으로 분리하기 위한 길이 0 체크 수행
    return len(gold[question_id]) == 0


